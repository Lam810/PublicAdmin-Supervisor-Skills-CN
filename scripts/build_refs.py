#!/usr/bin/env python3
"""Keep per-skill reference files in sync with their single sources of truth.

Every skill directory must stay self-contained (users may copy one skill
folder), so some references are duplicated:

- SHARED: a canonical hand-written file inside one skill, copied verbatim into
  other skills (only the leading HTML comment header differs);
- GENERATED: files rendered from vocab/*.yaml and rules/registry.yaml
  (plus rules/support.json when present).

    python scripts/build_refs.py --check   # exit 1 if anything is stale (CI)
    python scripts/build_refs.py --write   # regenerate / re-copy
"""

