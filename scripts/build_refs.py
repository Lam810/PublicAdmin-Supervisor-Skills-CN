def expected_files() -> dict[Path, str]:
    files: dict[Path, str] = {}
    for canonical, copies in SHARED.items():
        cpath = SKILLS / canonical
        if not cpath.exists():
            raise SystemExit(f"build_refs: canonical missing: skills/{canonical}")
        body = _strip_header(cpath.read_text(encoding="utf-8"))
        files[cpath] = (f"<!-- CANONICAL shared reference. Copies: {', '.join(c.split('/')[0] for c in copies)}. "
                        f"Edit here, then run scripts/build_refs.py --write. -->\n" + body)
        for c in copies:
            files[SKILLS / c] = f"<!-- COPY of skills/{canonical}; edit the canonical file and run scripts/build_refs.py --write. -->\n" + body
    for rel, fn in GENERATED.items():
        files[SKILLS / rel] = fn()
    files[REPO / "rules" / "preview" / "lens-cards-preview.md"] = render_lens_preview()
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    args = ap.parse_args()
    stale = []
    for path, content in expected_files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if args.write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    rel = [str(p.relative_to(REPO)) for p in stale]
    if args.check:
        if stale:
            print(f"build_refs: {len(stale)} stale file(s):")
            for r in rel:
                print(f"  {r}")
            print("run: python scripts/build_refs.py --write")
            return 1
        print(f"build_refs: {len(expected_files())} shared/generated file(s) in sync")
        return 0
    print(f"build_refs: wrote {len(stale)} file(s)" + ("".join(f"\n  {r}" for r in rel) if rel else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
